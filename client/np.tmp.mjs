import { boot, sleep, meas, btn } from '/tmp/harness.mjs';
const { server, React, act, root, host } = await boot();
const { default: NearPoint } = await server.ssrLoadModule('/src/patient/tests/NearPoint.jsx');
let results = [], fails = 0;
const ok = (c, msg) => { if (!c) { fails++; console.log('FAIL', msg); } else console.log('ok  ', msg); };
const render = async () => act(async () => root.render(React.createElement(NearPoint, { onDone: r => results.push(r) })));
const setM = async (m, histMm) => { globalThis.__fm.m = m; globalThis.__fm.history.current = (histMm || []).map((d, i) => ({ t: performance.now() - i * 20, m: meas({ distMm: d }) })); await render(); };
const feed = async mm => { const f = globalThis.__fm; f.history.current = [0, 1, 2, 3].map(i => ({ t: performance.now() - i * 30, m: meas({ distMm: mm }) })); f.m = meas({ distMm: mm }); await act(async () => { await sleep(260); }); };
await render();
ok(btn(host, /Start/).disabled, 'Start disabled with no face');
await setM(meas({ distMm: 200 }), [200]);
ok(btn(host, /Start/).disabled && /arm/.test(host.textContent), 'Start disabled and hint shown when too close (20 cm)');
await setM(meas({ distMm: 500, issues: ['small'] }), [500]);
ok(btn(host, /Start/).disabled, 'Start disabled when iris reading is unusable');
await setM(meas({ distMm: 500 }), [500]);
ok(!btn(host, /Start/).disabled, 'Start enabled at 50 cm with a clean reading');
await act(async () => btn(host, /Start/).click());
ok(!!btn(host, /blurry/i), 'moving phase shows the blurry button');
await feed(450); ok(/45 cm/.test(host.textContent), 'gauge shows smoothed live distance (45 cm)');
globalThis.__fm.history.current = []; globalThis.__fm.m = null; await render();
await act(async () => btn(host, /blurry/i).click());
ok(/not in view/.test(host.textContent) && results.length === 0, 'blur tap with no face gives a message and stores nothing');
await feed(300);
await act(async () => btn(host, /blurry/i).click());
ok(/30 cm/.test(host.textContent) && /\+0\.75/.test(host.textContent), 'blur at 30 cm -> result 30 cm, add +0.75');
ok(globalThis.__cam.stops >= 1, 'camera stopped when the test finished');
await act(async () => btn(host, /Continue/).click());
ok(JSON.stringify(results.at(-1)) === '{"cm":30,"add":0.75}', 'Continue returns exactly {cm, add}: ' + JSON.stringify(results.at(-1)));
results = []; await act(async () => btn(host, /Measure again/).click());
await setM(meas({ distMm: 500 }), [500]);
await act(async () => btn(host, /Start/).click());
await feed(140);
ok(/stayed clear/.test(host.textContent) && /\+0\.00/.test(host.textContent), 'reaching 14 cm without blur -> add 0, "stayed clear"');
await act(async () => btn(host, /Continue/).click());
ok(JSON.stringify(results.at(-1)) === '{"cm":14,"add":0}', 'auto-stop returns {cm:14, add:0}: ' + JSON.stringify(results.at(-1)));
results = []; await act(async () => btn(host, /Measure again/).click());
await setM(meas({ distMm: 500 }), [500]);
await act(async () => btn(host, /Start/).click());
await feed(1800);
await act(async () => btn(host, /blurry/i).click());
ok(/did not look right/.test(host.textContent) && results.length === 0, '180 cm reading is rejected, nothing stored');
await act(async () => btn(host, /Skip this test/).click());
ok(JSON.stringify(results.at(-1)) === '{}', 'Skip returns {}');
await server.close(); process.exit(fails ? 1 : 0);
